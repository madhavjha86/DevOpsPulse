"""Cloud Architecture Canvas Service for visual IaC and Terraform generation."""

from __future__ import annotations

from datetime import datetime, timezone
import uuid
from typing import Any

from app.core.logging import get_logger
from app.schemas.iac_canvas import (
    CanvasApplyRequest,
    CanvasApplyResponse,
    CanvasDiagram,
    CanvasEdge,
    CanvasGenerateTerraformRequest,
    CanvasGenerateTerraformResponse,
    CanvasNode,
)

logger = get_logger("iac_canvas_service")


class IACCanvasService:
    """Transforms interactive visual canvas graphs into production-grade Terraform HCL."""

    # In-memory saved user diagrams
    _saved_diagrams: dict[str, dict[str, Any]] = {}

    @classmethod
    def list_diagrams(cls) -> list[CanvasDiagram]:
        """Return all saved architecture diagrams."""
        return [CanvasDiagram(**d) for d in cls._saved_diagrams.values()]

    @classmethod
    def get_diagram(cls, diagram_id: str) -> CanvasDiagram | None:
        """Fetch a specific diagram by ID."""
        data = cls._saved_diagrams.get(diagram_id)
        if not data:
            return None
        return CanvasDiagram(**data)

    @classmethod
    def save_diagram(cls, diagram: CanvasDiagram) -> CanvasDiagram:
        """Save or update an architecture diagram."""
        cls._saved_diagrams[diagram.id] = diagram.model_dump()
        return diagram

    @classmethod
    def generate_terraform(
        cls, req: CanvasGenerateTerraformRequest
    ) -> CanvasGenerateTerraformResponse:
        """Synthesize production Terraform HCL from node graphs with monthly cost and security checks."""
        hcl_blocks = [
            f'# Generated by DevOpsPulse Cloud Architecture Engine\n'
            f'# Environment: {req.environment} | Region: {req.region}\n'
            f'terraform {{\n  required_version = ">= 1.5.0"\n  required_providers {{\n    aws = {{\n      source  = "hashicorp/aws"\n      version = "~> 5.0"\n    }}\n  }}\n}}\n\n'
            f'provider "aws" {{\n  region = "{req.region}"\n  default_tags {{\n    tags = {{\n      ManagedBy   = "DevOpsPulse"\n      Environment = "{req.environment}"\n    }}\n  }}\n}}\n'
        ]

        cost = 0.0
        warnings: list[str] = []
        node_counts = {t: 0 for t in ["vpc", "subnet", "ec2", "rds", "s3", "eks", "alb", "lambda", "redis"]}

        for node in req.nodes:
            node_counts[node.type] = node_counts.get(node.type, 0) + 1
            safe_name = node.label.lower().replace(" ", "_").replace("-", "_").replace("(", "").replace(")", "").replace("/", "_")
            if not safe_name.isidentifier():
                safe_name = f"{node.type}_{node.id.replace('-', '_')}"

            if node.type == "vpc":
                cidr = node.config.get("cidr_block", "10.0.0.0/16")
                hcl_blocks.append(
                    f'resource "aws_vpc" "{safe_name}" {{\n'
                    f'  cidr_block           = "{cidr}"\n'
                    f'  enable_dns_hostnames = true\n'
                    f'  enable_dns_support   = true\n'
                    f'  tags = {{\n    Name = "{node.label}"\n  }}\n}}\n'
                )
            elif node.type == "ec2":
                inst_type = node.config.get("instance_type", "t3.medium")
                count = int(node.config.get("count", 2))
                cost += 30.36 * count
                hcl_blocks.append(
                    f'resource "aws_instance" "{safe_name}" {{\n'
                    f'  count         = {count}\n'
                    f'  ami           = "ami-0c7217cdde317cfec" # Amazon Linux 2023\n'
                    f'  instance_type = "{inst_type}"\n'
                    f'  monitoring    = true\n'
                    f'  tags = {{\n    Name = "{node.label}-${{count.index + 1}}"\n  }}\n}}\n'
                )
            elif node.type == "rds":
                engine = node.config.get("engine", "postgres")
                instance_class = node.config.get("instance_class", "db.t3.medium")
                storage = int(node.config.get("storage", 50))
                cost += 68.40 + (storage * 0.115)
                hcl_blocks.append(
                    f'resource "aws_db_instance" "{safe_name}" {{\n'
                    f'  identifier          = "{safe_name}-db"\n'
                    f'  engine              = "{engine}"\n'
                    f'  instance_class      = "{instance_class}"\n'
                    f'  allocated_storage   = {storage}\n'
                    f'  storage_encrypted   = true\n'
                    f'  skip_final_snapshot = false\n'
                    f'  deletion_protection = true\n'
                    f'  tags = {{\n    Name = "{node.label}"\n  }}\n}}\n'
                )
            elif node.type == "s3":
                cost += 4.50
                hcl_blocks.append(
                    f'resource "aws_s3_bucket" "{safe_name}" {{\n'
                    f'  bucket = "devopspulse-{safe_name}-${{random_id.vault.hex}}"\n'
                    f'}}\n\n'
                    f'resource "aws_s3_bucket_server_side_encryption_configuration" "{safe_name}_sec" {{\n'
                    f'  bucket = aws_s3_bucket.{safe_name}.id\n'
                    f'  rule {{\n    apply_server_side_encryption_by_default {{\n      sse_algorithm = "AES256"\n    }}\n  }}\n}}\n'
                )
            elif node.type == "alb":
                cost += 22.50
                hcl_blocks.append(
                    f'resource "aws_lb" "{safe_name}" {{\n'
                    f'  name               = "{safe_name[:28]}"\n'
                    f'  internal           = false\n'
                    f'  load_balancer_type = "application"\n'
                    f'  drop_invalid_header_fields = true\n'
                    f'  tags = {{\n    Name = "{node.label}"\n  }}\n}}\n'
                )
            elif node.type == "eks":
                cost += 73.00 + 60.00
                hcl_blocks.append(
                    f'module "eks_{safe_name}" {{\n'
                    f'  source  = "terraform-aws-modules/eks/aws"\n'
                    f'  version = "~> 19.0"\n'
                    f'  cluster_name = "{safe_name}-cluster"\n'
                    f'  cluster_version = "1.29"\n'
                    f'}}\n'
                )
            elif node.type == "redis":
                cost += 28.00
                hcl_blocks.append(
                    f'resource "aws_elasticache_cluster" "{safe_name}" {{\n'
                    f'  cluster_id           = "{safe_name[:20]}"\n'
                    f'  engine               = "redis"\n'
                    f'  node_type            = "cache.t4g.micro"\n'
                    f'  num_cache_nodes      = 1\n'
                    f'  parameter_group_name = "default.redis7"\n'
                    f'}}\n'
                )
            elif node.type == "lambda":
                cost += 2.00
                hcl_blocks.append(
                    f'resource "aws_lambda_function" "{safe_name}" {{\n'
                    f'  function_name = "{safe_name}"\n'
                    f'  runtime       = "python3.12"\n'
                    f'  handler       = "index.handler"\n'
                    f'  role          = aws_iam_role.lambda_exec.arn\n'
                    f'}}\n'
                )

        # Check security best practices
        if node_counts.get("vpc", 0) == 0 and len(req.nodes) > 0:
            warnings.append("Architecture lacks an isolated Virtual Private Cloud (VPC); workloads would default to default public network.")
        if node_counts.get("alb", 0) > 0 and node_counts.get("ec2", 0) == 0 and node_counts.get("eks", 0) == 0:
            warnings.append("Load balancer has no target backend compute instance configured.")
        if node_counts.get("rds", 0) > 0:
            warnings.append("Ensure RDS database subnet groups reside in strictly private subnets with no internet gateway route.")

        full_hcl = "\n".join(hcl_blocks)
        summary = (
            f"Synthesized {len(req.nodes)} cloud resources and {len(req.edges)} network attachments into "
            f"AWS Terraform HCL. Monthly cost estimate: ${cost:.2f}/mo."
        )

        return CanvasGenerateTerraformResponse(
            hcl_code=full_hcl,
            resource_count=len(req.nodes),
            estimated_cost_monthly_usd=round(cost, 2),
            security_warnings=warnings,
            architecture_summary=summary,
        )

    @classmethod
    def apply_terraform(cls, req: CanvasApplyRequest) -> CanvasApplyResponse:
        """Simulate or dry-run Terraform Plan & Apply."""
        return CanvasApplyResponse(
            plan_status="SUCCESS",
            output=(
                f"Terraform used the selected providers to generate the following execution plan.\n"
                f"Resource actions are indicated with the following symbols:\n"
                f"  + create\n\n"
                f"Plan: 5 to add, 0 to change, 0 to destroy.\n\n"
                f"Apply complete! Resources: 5 added, 0 changed, 0 destroyed.\n"
                f"Outputs:\n"
                f"alb_dns_name = \"devopspulse-alb-pub-84192.us-east-1.elb.amazonaws.com\"\n"
                f"rds_endpoint = \"devopspulse-db.c8v2x.us-east-1.rds.amazonaws.com:5432\"\n"
                f"state_lock_id = \"md5:8f9a2b4c1e09\"\n"
            ),
            resources_to_add=5,
            resources_to_change=0,
            resources_to_destroy=0,
            duration_seconds=3.42,
        )
